/**
 * Writes the generated SCSS of a build target to disk:
 *
 * ```
 * srl/config.scss            design tokens with the system values of the current target
 * srl/colors.scss            colour functions
 * srl/typography.scss        typography mixins
 * srl/index.scss             `@use 'srl'` entry (placeholders + forwards)
 * srl/{system,…}.scss        static module files (see stubs.ts)
 * srl/fa/*.scss              Font Awesome helpers
 * .srl/scss/entries/<target>.scss   the stylesheet entry of the target
 * .srl/scss/entries/fonts.scss      remote font CSS of the hosted design
 * ```
 *
 * `srl/` is a real folder in the project (gitignored), like in SRL 1, so IDEs resolve
 * `@use 'srl'` and `@use 'srl/typography'` without knowing the Vite alias and offer the
 * mixins and functions. All targets share it; only `config.scss` differs per target
 * (`$build`, `$size-unit`, `$environment`), so it is rewritten before each target build.
 * Builds run one after another, so this is safe. The Vite/Sass alias `srl` points to it.
 * Files are only written when their content changed, so watchers are not triggered
 * needlessly.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import type { SrlConfig } from '../config/types'
import {
  renderIndexScss,
  renderScssEntries,
  resolveDesignBaseUrl,
  scanScssSources,
  type DesignInfo,
  type ScssSourceDirs,
  type ScssSources,
} from './scssEntries'
import { SRL_SCSS_STUBS } from './stubs'
import { renderTokens, systemValuesFor, type SrlBuildTarget, type SrlSystemValues } from './tokens'

export const DEFAULT_SRL_SCSS_OUT_DIR = '.srl/scss'
/** Folder of the generated `srl` SCSS module, relative to the project root. */
export const DEFAULT_SRL_DIR = 'srl'
/** First line of every generated file in `srl/`. */
export const SRL_GENERATED_HEADER =
  '// Generated by @simple-reporting/core from srl.config. Do not edit: changes are overwritten.'
/** Per-target module folders of older cores (.srl/scss/<target>/), removed on the next write. */
const LEGACY_TARGET_DIRS = ['app', 'editor', 'pdf', 'word', 'xbrl']

export type FontAwesomeType = 'free' | 'pro'

export interface WriteSrlScssOptions {
  rootDir: string
  /** Output folder of the entries, relative to `rootDir` or absolute. Default `.srl/scss`. */
  outDir?: string
  /** Folder of the `srl` module, relative to `rootDir` or absolute. Default `srl`. */
  srlDir?: string
  target: SrlBuildTarget
  config: SrlConfig
  /** Default: `production`. */
  environment?: SrlSystemValues['environment']
  /** Override the system values entirely (default: {@link systemValuesFor}). */
  system?: SrlSystemValues
  /** Source folders, see {@link DEFAULT_SCSS_SOURCE_DIRS}. */
  dirs?: ScssSourceDirs
  /**
   * Hosted design used for the remote font CSS. Defaults: base URL from
   * `SRL_EDITOR_DESIGN_URL` / `INTERNAL_LDD_URL`, name and version from the
   * project's `package.json`.
   */
  design?: Partial<DesignInfo>
  /** Pre-scanned sources (to share one scan between targets). */
  sources?: ScssSources
  /** Font Awesome free or pro. Default: {@link detectFontAwesomeType}. */
  faType?: FontAwesomeType
}

export interface WriteSrlScssResult {
  /** Absolute folder the `srl` alias must point to. */
  srlDir: string
  /** Absolute path of the target's entry stylesheet. */
  entry: string
  /** All files that belong to this target (absolute). */
  files: string[]
  /** Files whose content actually changed (absolute). */
  written: string[]
  warnings: string[]
}

/**
 * Generates and writes the SCSS of one target. Returns what was written.
 */
export async function writeSrlScss(options: WriteSrlScssOptions): Promise<WriteSrlScssResult> {
  const rootDir = path.resolve(options.rootDir)
  const outDir = path.resolve(rootDir, options.outDir ?? DEFAULT_SRL_SCSS_OUT_DIR)
  const { target } = options
  const srlDir = path.resolve(rootDir, options.srlDir ?? DEFAULT_SRL_DIR)
  const entriesDir = path.join(outDir, 'entries')
  const system = options.system ?? systemValuesFor(target, options.environment)
  const sources = options.sources ?? scanScssSources(rootDir, options.dirs)

  const tokens = renderTokens(options.config, system, {
    readFontStyles: (basePath, font) =>
      JSON.parse(readFileSync(path.join(rootDir, basePath, font, 'styles.json'), 'utf8')),
  })

  const pkg = readPackageJson(rootDir)
  const design: DesignInfo = {
    baseUrl: options.design?.baseUrl ?? resolveDesignBaseUrl(process.env),
    name: options.design?.name ?? pkg.name ?? 'design',
    version: options.design?.version ?? pkg.version ?? '0.0.0',
  }
  const entries = renderScssEntries(sources, {
    entriesDir,
    tokensDir: () => srlDir,
    design,
  })

  const files: Record<string, string> = {}
  for (const [name, content] of Object.entries(SRL_SCSS_STUBS)) {
    files[path.join(srlDir, name)] = content
  }
  files[path.join(srlDir, 'config.scss')] = tokens['config.scss']
  files[path.join(srlDir, 'colors.scss')] = tokens['colors.scss']
  files[path.join(srlDir, 'typography.scss')] = tokens['typography.scss']
  files[path.join(srlDir, 'index.scss')] = renderIndexScss(sources, { tokensDir: srlDir })
  // real files instead of the Vite aliases fa-source/fa-font, so IDEs can follow `@use 'srl/fa'`
  const faType = options.faType ?? detectFontAwesomeType(rootDir)
  files[path.join(srlDir, 'fa', 'source.scss')] = `@forward "source-${faType}";\n`
  files[path.join(srlDir, 'fa', 'font.scss')] = `@forward "font-${faType}";\n`
  const entry = path.join(entriesDir, `${target}.scss`)
  files[entry] = entries.files[`${target}.scss`]
  files[path.join(entriesDir, 'fonts.scss')] = entries.files['fonts.scss']

  for (const file of Object.keys(files)) {
    if (file.startsWith(srlDir + path.sep)) files[file] = `${SRL_GENERATED_HEADER}\n${files[file]}`
  }

  const written: string[] = []
  for (const [file, content] of Object.entries(files)) {
    if (await writeIfChanged(file, content)) written.push(file)
  }
  for (const legacy of LEGACY_TARGET_DIRS) {
    const dir = path.join(outDir, legacy)
    if (existsSync(dir)) await rm(dir, { recursive: true, force: true })
  }

  return { srlDir, entry, files: Object.keys(files), written, warnings: entries.warnings }
}

/** Writes `content` to `file` unless it already has exactly that content. */
export async function writeIfChanged(file: string, content: string): Promise<boolean> {
  try {
    if ((await readFile(file, 'utf8')) === content) return false
  } catch {
    // missing → write
  }
  await mkdir(path.dirname(file), { recursive: true })
  await writeFile(file, content)
  return true
}

/** `pro` if `@fortawesome/fontawesome-pro` is installed in the project, else `free`. */
export function detectFontAwesomeType(rootDir: string): FontAwesomeType {
  return existsSync(path.join(rootDir, 'node_modules', '@fortawesome', 'fontawesome-pro'))
    ? 'pro'
    : 'free'
}

/**
 * Sass/Vite aliases (SRL 1 `viteSrlPlugin`): `srl` → the module folder,
 * `fa-source`/`fa-font` → Font Awesome free or pro helpers inside it (kept for project files
 * that still use them; `srl/fa/source` and `srl/fa/font` also work in IDEs).
 */
export function srlScssAliases(
  srlDir: string,
  faType: FontAwesomeType = 'free',
): { srl: string; 'fa-source': string; 'fa-font': string } {
  return {
    srl: srlDir,
    'fa-source': path.join(srlDir, 'fa', `source-${faType}.scss`),
    'fa-font': path.join(srlDir, 'fa', `font-${faType}.scss`),
  }
}

function readPackageJson(rootDir: string): { name?: string; version?: string } {
  try {
    return JSON.parse(readFileSync(path.join(rootDir, 'package.json'), 'utf8'))
  } catch {
    return {}
  }
}

/**
 * Files in the `srl/` folder that core did not generate (no {@link SRL_GENERATED_HEADER}),
 * e.g. leftovers of SRL 1 (`srl/srl/`, `srl/.srl/`, `*.ts`). Relative to the project root.
 */
export function foreignSrlFiles(rootDir: string, srlDir: string = DEFAULT_SRL_DIR): string[] {
  const dir = path.resolve(rootDir, srlDir)
  if (!existsSync(dir)) return []
  const result: string[] = []
  const walk = (current: string) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name)
      if (entry.isDirectory()) walk(full)
      else if (!readFileSync(full, 'utf8').startsWith(SRL_GENERATED_HEADER)) {
        result.push(path.relative(rootDir, full).split(path.sep).join('/'))
      }
    }
  }
  walk(dir)
  return result.sort()
}
