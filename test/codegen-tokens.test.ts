import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { describeIf } from './describeIf'
import { renderTokens, systemValuesFor } from '../src/codegen/tokens'
import { renderUseSrlDesignConfig } from '../src/codegen/designConfig'
import type { SrlConfig } from '../src/config'
import testProjectConfig from './fixtures/srl1-test-project.config'

/** SRL 1 consumer project with generated output (sibling of srl2/ in the workspace). */
const TP = join(__dirname, '../../../../simple-reporting-library-test-project')
const hasTP = existsSync(join(TP, 'srl', 'config.scss'))

const golden = (file: string) =>
  readFileSync(join(TP, 'srl', file), 'utf8').replaceAll('@simple-reporting/base', '@simple-reporting/core')

describeIf(hasTP)('renderTokens – golden against SRL 1 test project', () => {
  // The test project's srl/ files were generated by the dev server: SRL 1
  // buildVariables = { system: { environment: 'development', build: 'app' } }.
  const json = JSON.parse(readFileSync(join(TP, 'srl.config.json'), 'utf8'))
  const out = renderTokens(json, { build: 'app', environment: 'development' })

  it('config.scss', () => expect(out['config.scss']).toBe(golden('config.scss')))
  it('colors.scss (incl. generated shades)', () => expect(out['colors.scss']).toBe(golden('colors.scss')))
  it('typography.scss', () => expect(out['typography.scss']).toBe(golden('typography.scss')))

  it('the TS fixture renders identically to the JSON', () => {
    expect(renderTokens(testProjectConfig, { build: 'app', environment: 'development' })).toEqual(out)
  })
})

describe('renderTokens', () => {
  const base: SrlConfig = {
    colors: { colors: [{ name: 'primary', color: '#ff0000' }] },
    typography: { typography: [{ name: 'body', 'font-size': 16 }] },
  }

  it('writes the system values first and lets them override the config', () => {
    const out = renderTokens(
      { ...base, system: { build: 'nope', 'root-size': 10 } },
      systemValuesFor('word'),
    )
    expect(out['config.scss'].split('\n').slice(0, 6).join('\n')).toBe(
      [
        '@use "@simple-reporting/core/scss/system/variables.scss" as systemVariables with (',
        '  $build: word,',
        '  $root-size: 10,',
        '  $environment: production,',
        '  $size-unit: pt',
        ');',
      ].join('\n'),
    )
  })

  it('uses rem for every target but word', () => {
    expect(systemValuesFor('pdf')['size-unit']).toBe('rem')
    expect(systemValuesFor('xbrl')['size-unit']).toBe('rem')
    expect(systemValuesFor('word')['size-unit']).toBe('pt')
  })

  it('ignores the project key and does not mutate the input', () => {
    const config: SrlConfig = { ...base, project: { livingdocs: { alternative: '@acme/ld' } } }
    const before = structuredClone(config)
    const a = renderTokens(config, systemValuesFor('app'))
    expect(config).toEqual(before)
    expect(a).toEqual(renderTokens(base, systemValuesFor('app')))
    expect(a['config.scss']).not.toContain('project')
    // no shared state between calls
    const pdf = renderTokens(config, systemValuesFor('pdf'))
    expect(pdf['config.scss']).toContain('$build: pdf')
    expect(renderTokens(config, systemValuesFor('app'))['config.scss']).toContain('$build: app')
  })

  it('quotes strings with dots or commas outside parentheses, but not sizes', () => {
    const out = renderTokens(
      {
        meta: {
          meta: {
            a: 'Inter, sans-serif',
            b: 'rgba(0,0,0,.5)',
            c: '1.5rem',
            d: 'say "hi", ok',
            e: '',
            f: '0.5',
            g: 'file.svg',
          },
        },
      },
      systemValuesFor('app'),
    )['config.scss']
    expect(out).toContain('a: "Inter, sans-serif"')
    expect(out).toContain('b: rgba(0,0,0,.5)')
    expect(out).toContain('c: 1.5rem')
    expect(out).toContain('d: "say \\"hi\\", ok"')
    expect(out).toContain('e: ""')
    expect(out).toContain('f: 0.5')
    expect(out).toContain('g: "file.svg"')
  })

  it('renders unnamed lists as var<index> maps', () => {
    const out = renderTokens({ helpers: { list: [1, 2] } as any }, systemValuesFor('app'))['config.scss']
    expect(out).toContain('$list: (\n    var0: 1,\n    var1: 2\n  )')
  })

  it('generates shades only when missing', () => {
    const out = renderTokens(
      {
        colors: {
          colors: [
            { name: 'shade', color: '#1677ff' },
            { name: 'shade-500', color: '#000000' },
          ],
        },
      },
      systemValuesFor('app'),
    )
    expect(out['config.scss']).toContain('shade-500: (\n      color: #000000\n    )')
    expect(out['config.scss']).toMatch(/shade-50: \(\n {6}color: #[0-9a-f]{6}\n/)
    expect(out['colors.scss']).toContain('@function shade-950()')
  })

  it('resolves fonts given by folder name and prefixes font-base-path', () => {
    const calls: string[] = []
    const out = renderTokens(
      { fonts: { 'font-base-path': '/assets/fonts', fonts: ['Inter', { name: 'Other' }] } },
      systemValuesFor('app'),
      {
        readFontStyles: (basePath, font) => {
          calls.push(`${basePath}|${font}`)
          return { name: font, types: [{ 'font-weight': 400 }] }
        },
      },
    )['config.scss']
    expect(calls).toEqual(['/assets/fonts|Inter'])
    expect(out).toContain('$font-base-path: "./assets/fonts"')
    expect(out).toContain('Inter: (')
    expect(out).toContain('Other: (')
    expect(() =>
      renderTokens({ fonts: { fonts: ['Inter'] } }, systemValuesFor('app')),
    ).toThrow(/readFontStyles/)
  })

  it('writes the section blocks in the SRL 1 order', () => {
    const out = renderTokens(
      { helpers: {}, spacer: { spacer: { '100': { size: 8 } } }, ...base, meta: { meta: {} } },
      systemValuesFor('app'),
    )['config.scss']
    const order = [...out.matchAll(/scss\/(\w+)\/variables\.scss/g)].map((m) => m[1])
    expect(order).toEqual(['system', 'meta', 'colors', 'typography', 'spacer', 'helpers'])
  })
})

describe('renderUseSrlDesignConfig', () => {
  it('exports the design tokens without the project key', () => {
    const src = renderUseSrlDesignConfig({ ...{ colors: { colors: [] } }, project: { livingdocs: {} } })
    expect(src).toContain(`import { ref } from 'vue'`)
    expect(src).toContain('export function useSrlDesignConfig()')
    expect(src).toContain('"colors"')
    expect(src).not.toContain('project')
  })
})
